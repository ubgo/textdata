func bytesOf(t *testing.T, f *generate.File) string {
	t.Helper()
	b, err := f.Bytes()
	if err != nil {
		t.Fatalf("Bytes: %v", err)
	}
	if _, err := jsonc.Parse(b); err != nil {
		t.Fatalf("output does not parse: %v\n%s", err, b)
	}
	return string(b)
}

func TestBuilderLayout(t *testing.T) {
	t.Parallel()
	f := generate.New(generate.SchemaURL("https://example.com/s.json"))
	f.Header("Generated by init.\nEdit freely.")
	f.Set("name", "demo", generate.Doc("The name."), generate.BlankBefore())
	srv := f.Object("server", generate.Doc("Server block"), generate.BlankBefore())
	srv.Set("port", 8080, generate.Trailing("default"))
	srv.Comment("host is optional")
	srv.Set("host", "<all>")
	f.Blank()
	hosts := f.Array("hosts")
	hosts.Add("a").Add("b", generate.Trailing("backup"))
	f.Set("empty", map[string]any{})
	f.Object("none")
	f.Set("raw", jsonc.Raw(`[1, /* two */ 2]`))
	f.Set("nested", map[string]any{"k": []int{1, 2}})
	want := `// Generated by init.
// Edit freely.
{
  "$schema": "https://example.com/s.json",

  // The name.
  "name": "demo",

  // Server block
  "server": {
    "port": 8080, // default
    // host is optional
    "host": "<all>"
  },

  "hosts": [
    "a",
    "b" // backup
  ],
  "empty": {},
  "none": {},
  "raw": [1, /* two */ 2],
  "nested": {
    "k": [
      1,
      2
    ]
  }
}
`
	if got := bytesOf(t, f); got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
}

func TestBuilderOptions(t *testing.T) {
	t.Parallel()
	build := func(opts ...generate.Option) *generate.File {
		f := generate.New(opts...)
		f.Header("head")
		o := f.Object("a", generate.Doc("doc"))
		o.Set("b", []int{1}, generate.Trailing("t"))
		f.Array("c").Add(true)
		return f
	}
	for _, tc := range []struct {
		name string
		opts []generate.Option
		want string
	}{
		{"tabs", []generate.Option{generate.Tabs()}, "// head\n{\n\t// doc\n\t\"a\": {\n\t\t\"b\": [\n\t\t\t1\n\t\t] // t\n\t},\n\t\"c\": [\n\t\ttrue\n\t]\n}\n"},
		{"four spaces", []generate.Option{generate.Spaces(4), generate.Comments(false)}, "{\n    \"a\": {\n        \"b\": [\n            1\n        ]\n    },\n    \"c\": [\n        true\n    ]\n}\n"},
		{"crlf", []generate.Option{generate.CRLF(), generate.Comments(false)}, "{\r\n  \"a\": {\r\n    \"b\": [\r\n      1\r\n    ]\r\n  },\r\n  \"c\": [\r\n    true\r\n  ]\r\n}\r\n"},
		{"trailing commas", []generate.Option{generate.TrailingCommas(true), generate.Comments(false), generate.FinalNewline(false)}, "{\n  \"a\": {\n    \"b\": [\n      1\n    ],\n  },\n  \"c\": [\n    true,\n  ],\n}"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if got := bytesOf(t, build(tc.opts...)); got != tc.want {
				t.Fatalf("got\n%q\nwant\n%q", got, tc.want)
			}
		})
	}
}

func TestBuilderCommentsOffIsStrictJSON(t *testing.T) {
	t.Parallel()
	f := generate.New(generate.Comments(false))
	f.Header("gone")
	f.Comment("gone too")
	f.Set("a", 1, generate.Doc("gone"), generate.Trailing("gone"))
	f.Object("only").Comment("gone") // an object holding only a comment is {}
	b, err := f.Bytes()
	if err != nil {
		t.Fatal(err)
	}
	if !json.Valid(b) {
		t.Fatalf("not JSON:\n%s", b)
	}
	if _, err := jsonc.Parse(b, jsonc.Strict()); err != nil {
		t.Fatalf("Strict: %v", err)
	}
}

func TestBuilderReplaceKey(t *testing.T) {
	t.Parallel()
	f := generate.New(generate.Comments(false))
	f.Set("a", 1).Set("b", 2).Set("a", 3)
	if got := bytesOf(t, f); got != "{\n  \"a\": 3,\n  \"b\": 2\n}\n" {
		t.Fatalf("got %q", got)
	}
}

func TestBuilderNestedArrays(t *testing.T) {
	t.Parallel()
	f := generate.New()
	arr := f.Array("matrix")
	arr.Array().Add(1).Add(2)
	arr.Comment("objects too") // a blank line keeps it off the next element
	arr.Blank()
	arr.Object(generate.Doc("first")).Set("x", 1)
	doc, err := f.Doc()
	if err != nil {
		t.Fatal(err)
	}
	if v, _ := doc.GetInt("matrix[1].x"); v != 1 {
		t.Fatalf("matrix[1].x = %d", v)
	}
	if c, _ := doc.Comment("matrix[1]"); c != "first" {
		t.Fatalf("comment %q", c)
	}
}

func TestBuilderErrors(t *testing.T) {
	t.Parallel()
	f := generate.New(generate.Indent("--"))
	if _, err := f.Bytes(); err == nil || !strings.Contains(err.Error(), "indent") {
		t.Fatalf("bad indent: %v", err)
	}
	f = generate.New()
	f.Set("ch", make(chan int))
	if _, err := f.Bytes(); err == nil || !strings.Contains(err.Error(), `key "ch"`) {
		t.Fatalf("unmarshalable value: %v", err)
	}
	f = generate.New()
	f.Array("a").Add(func() {})
	if _, err := f.Doc(); err == nil {
		t.Fatal("unmarshalable element must fail")
	}
}

// FuzzBuilder: any key, value and comment text gives a file that parses with
// zero errors and reads back the same key, value and comment.
func FuzzBuilder(f *testing.F) {
	f.Add("key", "value", "comment", "trail")
	f.Add("a.b", "line\nbreak", "two\nlines", "x\r\ny")
	f.Add("", "", "", "")
	f.Add("*/", "/*", "*/ /*", "// //")
	f.Add(" ", "<&>", "\r", "\x00")
	f.Fuzz(func(t *testing.T, key, value, comment, trailing string) {
		gen := generate.New()
		gen.Set(key, value, generate.Doc(comment), generate.Trailing(trailing))
		gen.Object("obj").Set(key, value, generate.Doc(comment))
		b, err := gen.Bytes()
		if err != nil {
			t.Fatalf("Bytes: %v", err) // strings always marshal
		}
		doc, err := jsonc.Parse(b)
		if err != nil {
			t.Fatalf("output does not parse: %v\n%q", err, b)
		}
		want := 2
		if key == "obj" {
			want = 1 // Object("obj") replaced the member
		}
		keys, err := doc.Keys("")
		if err != nil || len(keys) != want {
			t.Fatalf("keys %v %v\n%q", keys, err, b)
		}
		if key != "obj" && utf8.ValidString(key) && utf8.ValidString(value) {
			p := path.Path{path.Key(key)}.String()
			if got, err := doc.GetString(p); err != nil || got != value {
				t.Fatalf("GetString(%q) = %q, %v; want %q\n%q", p, got, err, value, b)
			}
		}
	})
}
